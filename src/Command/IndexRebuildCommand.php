namespace App\Command;

use App\Service\DirectoryIndexGenerator;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;

#[AsCommand(name: 'index:rebuild', description: 'Rebuild all the directory indexes.')]
class IndexRebuildCommand extends Command
{
  public function __construct(private readonly DirectoryIndexGenerator $generator)
  {
    parent::__construct();
  }

  protected function execute(InputInterface $input, OutputInterface $output): int
  {
    $count = $this->generator->rebuildAll();
    $output->writeln("Generated $count index files.");
    return self::SUCCESS;
  }
}
